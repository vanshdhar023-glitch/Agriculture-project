const languageSourceByTextNode = new WeakMap();
const languageSourceByAttribute = new WeakMap();
const languageSourceByChart = new WeakMap();
const languageAttributes = ['aria-label', 'alt', 'placeholder', 'title'];
let activeLanguage = 'en';
let languageObserver = null;

function getTranslationEntries(language) {
    const dictionary = agriTranslations[language];
    return dictionary ? { ...dictionary.terms, ...dictionary.phrases } : {};
}

function escapeTranslationRegex(text) {
    return text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function translateText(text, language = activeLanguage) {
    if (language === 'en') return text;
    const entries = getTranslationEntries(language);
    const normalized = text.trim();
    if (Object.prototype.hasOwnProperty.call(entries, normalized)) {
        return text.replace(normalized, entries[normalized]);
    }

    let translated = text;
    const sortedEntries = Object.entries(entries).sort(([left], [right]) => right.length - left.length);
    for (const [english, localized] of sortedEntries) {
        const expression = new RegExp(`(^|[^A-Za-z])${escapeTranslationRegex(english)}(?=$|[^A-Za-z])`, 'gi');
        translated = translated.replace(expression, (match, prefix) => `${prefix}${localized}`);
    }
    return translated;
}

function translateTextNode(node) {
    const previous = languageSourceByTextNode.get(node);
    const source = previous && node.nodeValue === previous.rendered ? previous.source : node.nodeValue;
    const rendered = translateText(source);
    languageSourceByTextNode.set(node, { source, rendered });
    if (node.nodeValue !== rendered) node.nodeValue = rendered;
}

function translateElementAttributes(element) {
    let attributes = languageSourceByAttribute.get(element);
    if (!attributes) {
        attributes = new Map();
        languageSourceByAttribute.set(element, attributes);
    }

    languageAttributes.forEach(attribute => {
        if (!element.hasAttribute(attribute)) return;
        const current = element.getAttribute(attribute);
        const previous = attributes.get(attribute);
        const source = previous && current === previous.rendered ? previous.source : current;
        const rendered = translateText(source);
        attributes.set(attribute, { source, rendered });
        if (current !== rendered) element.setAttribute(attribute, rendered);
    });
}

function translateTree(node) {
    if (node.nodeType === Node.TEXT_NODE) {
        if (node.parentElement && !['SCRIPT', 'STYLE', 'NOSCRIPT'].includes(node.parentElement.tagName)) {
            translateTextNode(node);
        }
        return;
    }
    if (node.nodeType !== Node.ELEMENT_NODE || ['SCRIPT', 'STYLE', 'NOSCRIPT'].includes(node.tagName)) return;

    translateElementAttributes(node);
    Array.from(node.childNodes).forEach(translateTree);
}

function translateChart(chart) {
    if (!chart || !chart.data || !chart.options) return;
    let source = languageSourceByChart.get(chart);
    if (!source) {
        source = {
            labels: Array.isArray(chart.data.labels) ? [...chart.data.labels] : null,
            datasetLabels: chart.data.datasets.map(dataset => dataset.label),
            title: chart.options.plugins?.title?.text,
            scaleTitles: Object.fromEntries(Object.entries(chart.options.scales || {}).map(([key, scale]) => [key, scale.title?.text]))
        };
        languageSourceByChart.set(chart, source);
    }

    if (source.labels && chart.data.labels) {
        chart.data.labels = source.labels.map(label => typeof label === 'string' ? translateText(label) : label);
    }
    chart.data.datasets.forEach((dataset, index) => {
        const label = source.datasetLabels[index];
        if (typeof label === 'string') dataset.label = translateText(label);
    });
    if (typeof source.title === 'string' && chart.options.plugins?.title) {
        chart.options.plugins.title.text = translateText(source.title);
    }
    Object.entries(source.scaleTitles).forEach(([key, title]) => {
        if (typeof title === 'string' && chart.options.scales?.[key]?.title) {
            chart.options.scales[key].title.text = translateText(title);
        }
    });
    chart.update('none');
}

function updateChartLanguage() {
    if (!window.Chart) return;
    window.Chart.defaults.locale = activeLanguage === 'hi' ? 'hi-IN' : activeLanguage === 'pa' ? 'pa-IN' : 'en-IN';
    Object.values(window.Chart.instances || {}).forEach(translateChart);
}

function setLanguage(language) {
    activeLanguage = Object.prototype.hasOwnProperty.call(agriTranslations, language) ? language : 'en';
    localStorage.setItem('agriPriceLanguage', activeLanguage);
    document.documentElement.lang = activeLanguage === 'en' ? 'en' : `${activeLanguage}-IN`;

    const selector = document.getElementById('languageSelector');
    if (selector) selector.value = activeLanguage;
    translateTree(document.body);
    updateChartLanguage();
}

function initializeLanguage() {
    const savedLanguage = localStorage.getItem('agriPriceLanguage') || 'en';
    activeLanguage = Object.prototype.hasOwnProperty.call(agriTranslations, savedLanguage) ? savedLanguage : 'en';
    document.documentElement.lang = activeLanguage === 'en' ? 'en' : `${activeLanguage}-IN`;

    const selector = document.getElementById('languageSelector');
    if (selector) selector.value = activeLanguage;
    translateTree(document.body);
    updateChartLanguage();

    if (!languageObserver) {
        languageObserver = new MutationObserver(records => {
            records.forEach(record => {
                if (record.type === 'characterData') translateTextNode(record.target);
                if (record.type === 'attributes') translateElementAttributes(record.target);
                record.addedNodes?.forEach(translateTree);
            });
        });
        languageObserver.observe(document.body, {
            attributes: true,
            attributeFilter: languageAttributes,
            characterData: true,
            childList: true,
            subtree: true
        });
    }
}

window.setLanguage = setLanguage;
window.addEventListener('DOMContentLoaded', initializeLanguage, { once: true });